// ---------------------------------------------------------------- text helpers

function words(text: string): string[] {
  return text
    .normalize('NFD')
    .replace(/[̀-ͯ]/g, '')
    .replace(/([a-z0-9])([A-Z])/g, '$1 $2')
    .split(/[^A-Za-z0-9]+/)
    .filter(Boolean)
    .map((word) => word.toLowerCase());
}

function camel(text: string): string {
  const [first = '', ...rest] = words(text);
  const name = first + rest.map(cap).join('');
  return /^[0-9]/.test(name) ? `_${name}` : name;
}

function pascal(text: string): string {
  return words(text).map(cap).join('');
}

/** `charges` to `charge`: a noun appended to a verb that acts on one item. */
function singular(word: string): string {
  if (/ies$/.test(word)) return word.replace(/ies$/, 'y');
  if (/(ss|x|ch|sh)es$/.test(word)) return word.replace(/es$/, '');
  if (/s$/.test(word) && !/(ss|us|is)$/.test(word)) return word.replace(/s$/, '');
  return word;
}

function cap(word: string): string {
  return word.charAt(0).toUpperCase() + word.slice(1);
}

/** Text safe to sit inside a JSDoc block: plain hyphens, no comment terminator. */
function clean(text: string): string {
  return text
    .replace(/[\u2014\u2013]/g, '-')
    .replace(/\*\//g, '*\\/')
    .replace(/[ \t]+$/gm, '')
    .trim();
}

/** A summary without the leading echo of its own route, which the docs print right below. */
function headline(summary: string): string {
  const text = clean(summary);
  const rest = text.replace(/^`(GET|POST|PUT|PATCH|DELETE) [^`]+`\s*[-:.,]?\s*/, '');
  return rest ? rest.charAt(0).toUpperCase() + rest.slice(1) : text;
}

function doc(lines: Array<string | undefined>, indent = ''): string {
  const body = lines
    .filter((line): line is string => line !== undefined)
    .join('\n')
    .replace(/\n{3,}/g, '\n\n')
    .replace(/^\n+|\n+$/g, '')
    .split('\n');
  if (body.length === 1 && body[0] === '') return '';
  if (body.length === 1) return `${indent}/** ${body[0]} */\n`;
  return `${indent}/**\n${body.map((line) => `${indent} *${line ? ` ${line}` : ''}`).join('\n')}\n${indent} */\n`;
}

function key(name: string): string {
  return /^[A-Za-z_$][A-Za-z0-9_$]*$/.test(name) ? name : JSON.stringify(name);
}

// ---------------------------------------------------------- schema to TypeScript

function refName(ref: string): string {
  return ref.split('/').pop()!;
}

/** `prefix` is `''` inside schemas.ts and `'S.'` in the resource files. */
function ts(schema: Json | undefined | boolean, prefix: string, indent = ''): string {
  if (schema === undefined || schema === true) return 'unknown';
  if (schema === false) return 'never';
  if (schema.$ref) return prefix + refName(schema.$ref);
  if (schema.oneOf || schema.anyOf) {
    return union((schema.oneOf ?? schema.anyOf).map((item: Json) => ts(item, prefix, indent)));
  }
  if (schema.allOf) {
    const parts = schema.allOf.map((item: Json) => ts(item, prefix, indent));
    if (schema.properties) parts.push(objectType(schema, prefix, indent));
    return parts.length === 1 ? parts[0] : parts.map((part: string) => (part.includes('|') ? `(${part})` : part)).join(' & ');
  }
  if ('const' in schema) return JSON.stringify(schema.const);
  if (schema.enum) return union(schema.enum.map((value: unknown) => JSON.stringify(value)));
  if (Array.isArray(schema.type)) {
    return union(schema.type.map((type: string) => ts({ ...schema, type }, prefix, indent)));
  }
  switch (schema.type) {
    case 'string':
      return schema.format === 'binary' ? 'Blob' : 'string';
    case 'integer':
    case 'number':
      return 'number';
    case 'boolean':
      return 'boolean';
    case 'null':
      return 'null';
    case 'array': {
      if (schema.prefixItems) return `[${schema.prefixItems.map((item: Json) => ts(item, prefix, indent)).join(', ')}]`;
      const item = ts(schema.items, prefix, indent);
      return /[|&]/.test(item) ? `Array<${item}>` : `${item}[]`;
    }
    case 'object':
      return objectType(schema, prefix, indent);
    default:
      return schema.properties || schema.additionalProperties ? objectType(schema, prefix, indent) : 'unknown';
  }
}

function union(parts: string[]): string {
  const unique = [...new Set(parts)];
  return unique.length === 0 ? 'never' : unique.join(' | ');
}

function objectType(schema: Json, prefix: string, indent: string): string {
  const properties: Json = schema.properties ?? {};
  const names = Object.keys(properties);
  const extra = schema.additionalProperties;
  const extraType = extra === undefined || extra === false ? undefined : ts(extra === true ? undefined : extra, prefix, indent + '  ');
  // A closed object with no properties is the `{}` some routes answer with.
  if (names.length === 0) return extra === false ? 'Record<string, never>' : `Record<string, ${extraType ?? 'unknown'}>`;
  const required = new Set<string>(schema.required ?? []);
  const inner = indent + '  ';
  let out = '{\n';
  for (const name of names) {
    const property = properties[name];
    out += doc([property.description ? clean(property.description) : undefined], inner);
    // A 64-bit id does not fit a JS number: the client hands it over as a string of digits.
    const wideId = /(^|_)id$/.test(name) && property.format === 'int64' && [property.type].flat().includes('integer');
    const type = ts(property, prefix, inner);
    out += `${inner}${key(name)}${required.has(name) ? '' : '?'}: ${wideId ? type.replace(/\bnumber\b/, 'number | string') : type};\n`;
  }
  if (extraType) out += `${inner}[key: string]: unknown;\n`;
  return `${out}${indent}}`;
}

function emitSchemas(): string {
  let out = `${HEADER}/* eslint-disable */\n\n`;
  for (const name of Object.keys(schemas).sort()) {
    const schema = schemas[name];
    out += doc([schema.description ? clean(schema.description) : undefined]);
    const plainObject =
      !schema.$ref && !schema.oneOf && !schema.anyOf && !schema.allOf && !schema.enum && !Array.isArray(schema.type) &&
      (schema.type === 'object' || schema.properties) && Object.keys(schema.properties ?? {}).length > 0;
    out += plainObject ? `export interface ${name} ${objectType(schema, '', '')}\n\n` : `export type ${name} = ${ts(schema, '', '')};\n\n`;
  }
  return out;
}

// ------------------------------------------------------------------ operations

interface Param {
  name: string;
  in: string;
  required: boolean;
  description?: string;
  schema?: Json;
}

interface Operation {
  method: string;
  path: string;
  id: string;
  tag: string;
  namespace: string[];
  name: string;
  summary?: string;
  description?: string;
  deprecated: boolean;
  secured: boolean;
  pathParams: Param[];
  queryParams: Param[];
  headerParams: Param[];
  body?: { type: string; kind: 'json' | 'binary' | 'form' | 'multipart'; required: boolean };
  response: { type: string; kind: 'json' | 'text' | 'raw' | 'void' | 'auto'; schema?: Json; redirect?: boolean };
  /** Items field of a paginated route; `null` when the document does not say and the client finds it at run time. */
  pageField?: string | null;
}

function resolveSchema(schema: Json | undefined): Json | undefined {
  let current = schema;
  for (let depth = 0; current?.$ref && depth < 10; depth++) current = schemas[refName(current.$ref)];
  return current;
}

function bodyOf(operation: Json): Operation['body'] {
  const content: Json | undefined = operation.requestBody?.content;
  if (!content) return undefined;
  const required = operation.requestBody.required === true;
  if (content['application/json']) return { type: ts(content['application/json'].schema, 'S.'), kind: 'json', required };
  if (content['multipart/form-data']) return { type: 'FormData', kind: 'multipart', required };
  if (content['application/x-www-form-urlencoded']) {
    return { type: 'Record<string, string> | URLSearchParams', kind: 'form', required };
  }
  return { type: 'Blob | ArrayBuffer | Uint8Array | ReadableStream<Uint8Array>', kind: 'binary', required };
}

function responseOf(operation: Json): Operation['response'] {
  const types: string[] = [];
  let kind: Operation['response']['kind'] = 'void';
  let schema: Json | undefined;
  for (const [status, response] of Object.entries<Json>(operation.responses ?? {})) {
    if (!status.startsWith('2')) continue;
    const content: Json | undefined = response.content;
    if (!content || Object.keys(content).length === 0) {
      // 202, 204 and 205 promise an empty body. Any other 2xx left undescribed is decoded at run time.
      if (status === '202' || status === '204' || status === '205') {
        types.push('void');
      } else {
        if (kind === 'void') kind = 'auto';
        types.push('unknown');
      }
      continue;
    }
    const mime = Object.keys(content)[0]!;
    if (content['application/json']) {
      kind = 'json';
      schema ??= content['application/json'].schema;
      types.push(ts(content['application/json'].schema, 'S.'));
    } else if (/^text\/(plain|csv)|xml/.test(mime)) {
      kind = 'text';
      types.push('string');
    } else {
      kind = 'raw';
      types.push('Response');
    }
  }
  // A route that only redirects is meant for a browser: hand the 3xx over untouched.
  const statuses = Object.keys(operation.responses ?? {});
  if (types.length === 0 && statuses.some((status) => status.startsWith('3'))) {
    return { type: 'Response', kind: 'raw', redirect: true };
  }
  return { type: types.includes('unknown') ? 'unknown' : union(types.length ? types : ['void']), kind, schema };
}

function pageFieldOf(queryParams: Param[], response: Operation['response']): string | null | undefined {
  if (!queryParams.some((param) => param.name === 'page_token')) return undefined;
  if (response.kind !== 'json' && response.kind !== 'auto') return undefined;
  const resolved = resolveSchema(response.schema);
  const properties: Json | undefined = resolved?.properties;
  if (!properties) return null;
  if (!properties.next_page_token) return undefined;
  const arrays = Object.keys(properties).filter((name) => resolveSchema(properties[name])?.type === 'array');
  if (arrays.includes('items')) return 'items';
  return arrays.length === 1 ? arrays[0]! : null;
}

function collect(): Operation[] {
  const operations: Operation[] = [];
  for (const [path, item] of Object.entries<Json>(spec.paths)) {
    for (const method of METHODS) {
      const operation: Json | undefined = item[method];
      if (!operation) continue;
      const order = [...path.matchAll(/\{([^}]+)\}/g)].map((match) => match[1]!);
      // The document marks some query parameters as `path`. One that is not in the
      // route can only travel in the query, and is optional because `required`
      // there is just what every path parameter carries.
      const params: Param[] = [...(item.parameters ?? []), ...(operation.parameters ?? [])].map((param: Param) =>
        param.in === 'path' && !order.includes(param.name) ? { ...param, in: 'query', required: false } : param,
      );
      const inPath = params.filter((param) => param.in === 'path');
      const queryParams = params.filter((param) => param.in === 'query');
      const response = responseOf(operation);
      const tag: string = operation.tags?.[0] ?? path.split('/')[2] ?? 'misc';
      operations.push({
        method: method.toUpperCase(),
        path,
        id: operation.operationId !== undefined ? untagged(operation.operationId, tag) : `${method}_${path}`,
        tag,
        namespace: tag.split('·').map((part) => camel(part)),
        name: '',
        summary: operation.summary,
        description: operation.description,
        deprecated: operation.deprecated === true,
        secured: Array.isArray(operation.security ?? spec.security) && (operation.security ?? spec.security).length > 0,
        pathParams: order.map((name) => inPath.find((param) => param.name === name) ?? { name, in: 'path', required: true }),
        queryParams,
        headerParams: params.filter((param) => param.in === 'header'),
        body: bodyOf(operation),
        response,
        pageField: pageFieldOf(queryParams, response),
      });
    }
  }
  return operations;
}

/**
 * The operation id without the tag prefix the gateway adds to keep ids unique
 * across the document (`auth_me`, `hooks_list_subscriptions`): inside the
 * resource the tag is already the namespace, so `api.auth.me()`.
 */
function untagged(id: string, tag: string): string {
  const prefix = `${words(tag.toLowerCase()).join('_')}_`;
  return id.startsWith(prefix) && id.length > prefix.length ? id.slice(prefix.length) : id;
}

/** Static path segments, minus the version prefix and a trailing echo of the operation id. */
function nouns(operation: Operation): string[] {
  const segments = operation.path.split('/').filter((segment) => segment && segment !== 'v1' && !segment.startsWith('{'));
  const idWords = new Set(words(operation.id));
  while (segments.length > 1 && words(segments[segments.length - 1]!).every((word) => idWords.has(word))) segments.pop();
  return segments;
}

/** Method names: the operation id, disambiguated by the path where a tag reuses it. */
function nameOperations(operations: Operation[], childNames: Map<string, Set<string>>): void {
  const groups = new Map<string, Operation[]>();
  for (const operation of operations) {
    const group = `${operation.namespace.join('.')}#${camel(operation.id)}`;
    groups.set(group, [...(groups.get(group) ?? []), operation]);
  }
  const taken = new Map<string, Set<string>>();
  const claim = (operation: Operation, candidates: string[]) => {
    const scope = operation.namespace.join('.');
    const used = taken.get(scope) ?? new Set<string>(childNames.get(scope) ?? []);
    taken.set(scope, used);
    // `xAll` is the paginated walk of `x`: a name whose `All` is already
    // another operation (`admit` next to `admitAll`) would collide with it.
    const free = (candidate: string) => !used.has(candidate) && !used.has(`${candidate}All`);
    let name = candidates.find(free);
    for (let n = 2; !name; n++) if (free(`${candidates[0]}${n}`)) name = `${candidates[0]}${n}`;
    used.add(name!);
    used.add(`${name}All`);
    operation.name = name!;
  };
  for (const group of groups.values()) {
    const base = camel(group[0]!.id);
    if (group.length === 1) {
      claim(group[0]!, [base, base + pascal(nouns(group[0]!).slice(-1)[0] ?? ''), `${base}Operation`]);
      continue;
    }
    const plural = /^(list|search|count)/.test(base);
    const lastNoun = (operation: Operation) => {
      const parts = words(nouns(operation).slice(-1)[0] ?? '');
      if (!plural && parts.length > 0) parts[parts.length - 1] = singular(parts[parts.length - 1]!);
      return parts.map(cap).join('');
    };
    const lastDistinct = new Set(group.map(lastNoun)).size === group.length;
    for (const operation of group) {
      const all = nouns(operation);
      claim(operation, [
        ...(lastDistinct ? [base + lastNoun(operation)] : []),
        base + pascal(all.slice(-2).join(' ')),
        base + pascal(all.join(' ')),
        base + pascal(`${operation.method} ${all.join(' ')}`),
      ]);
    }
  }
}

// ------------------------------------------------------------------- resources

interface Node {
  segments: string[];
  className: string;
  children: Map<string, Node>;
  operations: Operation[];
  tags: Set<string>;
}

function buildTree(operations: Operation[]): Node {
  const root: Node = { segments: [], className: 'Api', children: new Map(), operations: [], tags: new Set() };
  for (const operation of operations) {
    let node = root;
    for (const segment of operation.namespace) {
      let child = node.children.get(segment);
      if (!child) {
        const segments = [...node.segments, segment];
        child = { segments, className: segments.map(pascal).join('') + 'Resource', children: new Map(), operations: [], tags: new Set() };
        node.children.set(segment, child);
      }
      node = child;
    }
    node.operations.push(operation);
    node.tags.add(operation.tag);
  }
  return root;
}

function emitOperation(operation: Operation, node: Node): { types: string; methods: string } {
  const typeBase = node.segments.map(pascal).join('') + pascal(operation.name);
  let types = '';
  const args: string[] = [];
  const argDocs: string[] = [];
  const used = new Set(['body', 'query', 'options']);

  const pathArgs = operation.pathParams.map((param) => {
    let name = camel(param.name) || 'param';
    while (used.has(name)) name += '_';
    used.add(name);
    const type = ts(param.schema ?? { type: 'string' }, 'S.');
    args.push(`${name}: ${type === 'number' ? 'string | number' : type}`);
    argDocs.push(`@param ${name} ${clean(param.description ?? `Path parameter \`${param.name}\`.`).replace(/\n+/g, ' ')}`);
    return { param: param.name, name };
  });

  // A required argument cannot follow an optional one, so trailing arguments decide.
  const queryRequired = operation.queryParams.some((param) => param.required);
  const headersRequired = operation.headerParams.some((param) => param.required);
  if (operation.body) {
    const optional = !operation.body.required && !queryRequired && !headersRequired;
    args.push(`body${optional ? '?' : ''}: ${operation.body.type}${operation.body.required || optional ? '' : ' | undefined'}`);
    argDocs.push('@param body Request body.');
  }
  if (operation.queryParams.length > 0) {
    const queryType = `${typeBase}Query`;
    let fields = '';
    for (const param of operation.queryParams) {
      fields += doc([param.description ? clean(param.description) : undefined], '  ');
      fields += `  ${key(param.name)}${param.required ? '' : '?'}: ${ts(param.schema ?? { type: 'string' }, 'S.', '  ')};\n`;
    }
    types += `${doc([`Query of \`${operation.method} ${operation.path}\`.`])}export interface ${queryType} {\n${fields}}\n\n`;
    const optional = !queryRequired && !headersRequired;
    args.push(`query${optional ? '?' : ''}: ${queryType}${queryRequired || optional ? '' : ' | undefined'}`);
    argDocs.push('@param query Query string parameters.');
  }
  let optionsType = 'RequestOptions';
  if (operation.headerParams.length > 0) {
    const fields = operation.headerParams.map((param) => `${key(param.name)}${param.required ? '' : '?'}: string`).join('; ');
    optionsType = `RequestOptions & { headers${headersRequired ? '' : '?'}: { ${fields} } }`;
    argDocs.push(`@param options Per-call overrides. Headers of this route: ${operation.headerParams.map((param) => `\`${param.name}\`${param.required ? ' (required)' : ''}`).join(', ')}.`);
  } else {
    argDocs.push('@param options Per-call overrides.');
  }
  args.push(`options${headersRequired ? '' : '?'}: ${optionsType}`);

  const url = operation.path.replace(/\{([^}]+)\}/g, (_, name: string) => `\${seg(${pathArgs.find((arg) => arg.param === name)!.name})}`);
  const fields = [`method: '${operation.method}'`, `path: \`${url}\``];
  if (operation.queryParams.length > 0) fields.push('query');
  if (operation.body) {
    fields.push('body');
    if (operation.body.kind !== 'json') fields.push(`bodyType: '${operation.body.kind}'`);
  }
  if (operation.response.kind !== 'json') fields.push(`responseType: '${operation.response.kind}'`);
  if (operation.response.redirect) fields.push("redirect: 'manual'");
  if (!operation.secured) fields.push('auth: false');
  fields.push('options');

  const summary = operation.summary ? headline(operation.summary) : undefined;
  const description = operation.description ? clean(operation.description) : undefined;
  const route = `\`${operation.method} ${operation.path}\`${operation.secured ? '' : ' (public route, sent without credentials)'}`;
  const header = [summary, summary && description ? '' : undefined, description, '', route, ''];
  let methods = doc([...header, ...argDocs, operation.deprecated ? '@deprecated' : undefined], '  ');
  methods += `  ${operation.name}(${args.join(', ')}): Promise<${operation.response.type}> {\n`;
  methods += `    return this._http.request({ ${fields.join(', ')} });\n  }\n\n`;

  if (operation.pageField !== undefined) {
    const item = operation.pageField === null ? 'unknown' : `NonNullable<${operation.response.type}[${JSON.stringify(operation.pageField)}]>[number]`;
    const allArgs = args.filter((arg) => !arg.startsWith('query') && !arg.startsWith('options'));
    const queryType = `${typeBase}Query`;
    const call = [...pathArgs.map((arg) => arg.name), ...(operation.body ? ['body'] : []), '{ ...query, page_token } as ' + queryType, 'options'];
    methods += doc(
      [
        `Iterates every item of \`${operation.name}\`, following \`next_page_token\` page after page.`,
        '',
        route,
      ],
      '  ',
    );
    methods += `  ${operation.name}All(${[...allArgs, `query${queryRequired ? '' : '?'}: ${queryType}`, `options${headersRequired ? '' : '?'}: ${optionsType}`].join(', ')}): Paginator<${item}, ${operation.response.type}> {\n`;
    methods += `    return new Paginator((page_token) => this.${operation.name}(${call.join(', ')}), ${operation.pageField === null ? 'undefined' : JSON.stringify(operation.pageField)}, query?.page_token ?? undefined);\n  }\n\n`;
  }
  return { types, methods };
}

function emitNode(node: Node): string {
  let types = '';
  let body = '';
  let nested = '';
  for (const [name, child] of [...node.children].sort(([a], [b]) => a.localeCompare(b))) {
    nested += emitNode(child);
    body += `  readonly ${name} = new ${child.className}(this._http);\n`;
  }
  if (body) body += '\n';
  for (const operation of [...node.operations].sort((a, b) => a.name.localeCompare(b.name))) {
    const emitted = emitOperation(operation, node);
    types += emitted.types;
    body += emitted.methods;
  }
  const title = node.tags.size > 0 ? [...node.tags].join(', ') : node.segments.join(' · ');
  return `${nested}${types}${doc([`Routes tagged \`${clean(title)}\`.`])}export class ${node.className} extends Resource {\n${body.trimEnd()}\n}\n\n`;
}

function fileName(segment: string): string {
  return words(segment).join('-');
}

// ------------------------------------------------------------------------ main

const operations = collect();
const childNames = new Map<string, Set<string>>();
for (const operation of operations) {
  for (let depth = 0; depth < operation.namespace.length; depth++) {
    const scope = operation.namespace.slice(0, depth).join('.');
    childNames.set(scope, (childNames.get(scope) ?? new Set()).add(operation.namespace[depth]!));
  }
}
nameOperations(operations, childNames);
const tree = buildTree(operations);

// ------------------------------------------------------------ version guard
//
// `openapi/version.json` records which package version was generated from which
// document. A new document needs a new version, and a change that breaks code
// written against the previous one (a method gone or renamed, a field or enum
// value gone, a field or parameter retyped, a parameter gone, a request field or
// parameter that became required) needs a minor bump while the
// SDK is 0.x and a major bump after 1.0. The check runs before any file is
// written, so a refused run leaves the tree as it was.

const LOCK = join(ROOT, 'openapi/version.json');
const snapshotText = snapshotOf(spec);
const specSha = sha256(snapshotText);
const minSha = sha256(minifiedText(snapshotText));
const version: string = JSON.parse(readFileSync(join(ROOT, 'package.json'), 'utf8')).version;

function readJson(path: string): any {
  try {
    return JSON.parse(readFileSync(path, 'utf8'));
  } catch {
    return undefined;
  }
}

/** What code written against `before` would stop compiling or working on. */
function breakingChanges(before: Json, beforeOps: { method: string; path: string; name: string }[]): string[] {
  const out: string[] = [];
  const now = new Map(operations.map((operation) => [`${operation.method} ${operation.path}`, operation.name]));
  for (const old of beforeOps) {
    const name = now.get(`${old.method} ${old.path}`);
    if (name === undefined) out.push(`operation removed: ${old.method} ${old.path} (${old.name})`);
    else if (name !== old.name) out.push(`method renamed: ${old.name} -> ${name} (${old.method} ${old.path})`);
  }
  return out.concat(breakingSpecChanges(before, spec));
}

// The edge contract, byte for byte as LF.
let edgeText: string | undefined;
try {
  edgeText = readFileSync(EDGE_SOURCE ?? EDGE, 'utf8').replace(/\r/g, '');
} catch {
  if (EDGE_SOURCE) throw new Error(`cannot read the edge contract ${EDGE_SOURCE}`);
}
if (edgeText !== undefined) {
  const edge = JSON.parse(edgeText);
  if (typeof edge?.schema_version !== 'number') throw new Error('the edge contract has no numeric schema_version');
}
const edgeSha = edgeText === undefined ? undefined : sha256(edgeText);

const fail = (message: string): never => {
  console.error(message);
  process.exit(1);
};
const lock = readJson(LOCK) as { version: string; spec_sha256: string; edge_contract_sha256?: string } | undefined;
if (lock) {
  const specChanged = lock.spec_sha256 !== specSha;
  const edgeChanged = lock.edge_contract_sha256 !== edgeSha;
  if (lock.version === version) {
    if (specChanged || edgeChanged) {
      fail(`the ${specChanged ? 'OpenAPI document' : 'edge contract'} changed: bump the version in package.json and src/version.ts (still ${version}) before generating`);
    }
  } else {
    const breaking = specChanged ? breakingChanges(readJson(SNAPSHOT) ?? {}, readJson(join(ROOT, 'openapi/operations.json')) ?? []) : [];
    const bump = requiredBump(breaking.length > 0, specChanged || edgeChanged);
    const accepted = acceptedVersions(lock.version, bump);
    if (!accepted.includes(version)) {
      const why = breaking.length > 0 ? `${breaking.length} breaking changes` : specChanged || edgeChanged ? 'new in the spec or the edge contract, nothing breaking' : 'same spec and edge contract';
      fail(
        `${why}: this is a ${bump} bump, so ${lock.version} -> ${accepted.join(' or ')} (got ${version})${breaking.length > 0 ? `:\n  ${breaking.slice(0, 30).join('\n  ')}` : ''}`,
      );
    }
    console.log(`${bump} bump, ${lock.version} -> ${version}${breaking.length > 0 ? `, ${breaking.length} breaking changes` : ''}`);
  }
}

