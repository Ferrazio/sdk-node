/**
 * Generates `src/generated/**` and `docs/api.md` from the gateway OpenAPI document.
 *
 *   bun scripts/generate.ts [path-or-url-to-openapi.json] [path-to-edge-contract.json]
 *
 * Without an argument it reads `FERRAZIO_OPENAPI`, then the snapshot in
 * `openapi/openapi.json`. Whatever document is used is saved back as that
 * snapshot, so a build is reproducible and a change of the API shows as a diff.
 * `openapi/operations.json` maps every operation to its SDK method.
 *
 * The second argument (or `FERRAZIO_EDGE_CONTRACT`) is the `edge-contract.json`
 * of the same gateway commit: the edge behavior a client can observe (CORS,
 * headers, account hold, error reasons). It is copied as LF text to
 * `openapi/edge-contract.json` and its hash goes to `openapi/version.json` as
 * `edge_contract_sha256`. Without it the copy already there is kept.
 */
